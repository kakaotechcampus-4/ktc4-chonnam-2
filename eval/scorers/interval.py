"""비율 지표의 신뢰구간.

**왜 필요한가.** B tier 정답지의 채점 대상 사건이 10건이고, `by_type` 은
유형당 2~6건이다. SIGNAL 2건에서 나올 수 있는 recall 은 0 · 0.5 · 1 셋뿐인데,
결과 파일은 `0.5` 라고만 적는다 — 소수점이 정밀해 보인다. 그 값이 실제로
얼마나 흔들리는지를 결과가 스스로 말해야 한다.

**왜 Wilson 인가.** 흔히 쓰는 정규근사(Wald)는 `p ± z·sqrt(p(1-p)/n)` 인데,
우리가 실제로 마주치는 자리에서 정확히 무너진다:

- `k=n` 이면 분산이 0 이라 **[1.0, 1.0]** 을 낸다. 2건 맞혔다고 「확실히 100%」다
- `k=0` 이면 같은 이유로 [0, 0]
- 표본이 작으면 구간이 0 아래나 1 위로 샌다

Wilson score 구간은 같은 자리에서 서지 않는 값을 내지 않는다. 표본이 작을수록
비대칭으로 넓어지는 것도 실제 불확실성의 모양에 맞는다.

**평균에는 쓰지 않는다.** `onset_error_sec` 은 비율이 아니라 평균이고,
`fp_per_clip` 은 0~1 로 묶이지 않는 비율이다 — 둘 다 이 구간의 가정 밖이다.
"""
import math

Z95 = 1.959963984540054
"""표준정규 97.5% 분위. 95% 양측 구간."""


def wilson95(hits, total):
    """Wilson score 95% 구간. 분모가 0 이면 `None`.

    반환은 `(하한, 상한)` 이고 둘 다 [0, 1] 안이다.
    """
    if not total:
        # 잴 게 없었다. 0.0 이 아니라 구간 자체가 없다.
        return None
    p = hits / total
    d = 1 + Z95 * Z95 / total
    center = (p + Z95 * Z95 / (2 * total)) / d
    half = Z95 * math.sqrt(p * (1 - p) / total
                           + Z95 * Z95 / (4 * total * total)) / d
    return (max(0.0, center - half), min(1.0, center + half))
